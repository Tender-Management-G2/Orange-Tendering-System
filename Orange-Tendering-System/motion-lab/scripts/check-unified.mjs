import { chromium } from 'playwright-core';
import { writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import assert from 'node:assert/strict';

const output=resolve(import.meta.dirname,'..','evidence','unified');
const browser=await chromium.launch({executablePath:'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe',headless:true,args:['--enable-webgl']});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[],externalRequests=[],states=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('request',request=>{if(!request.url().startsWith('http://127.0.0.1:4173/'))externalRequests.push(request.url());});
const state=()=>page.evaluate(()=>window.motionLab.getState());
async function progressNear(target){await page.waitForFunction(value=>{const s=window.motionLab.getState();return !s.transitioning&&Math.abs(s.progress-value)<.001;},target,{timeout:8000});states.push({target,actual:(await state()).progress});}
await page.goto('http://127.0.0.1:4173',{waitUntil:'networkidle'});
await page.waitForFunction(()=>Boolean(window.motionLab));await progressNear(.14);
assert.equal(await page.locator('#reg-iris').isDisabled(),true);
await page.locator('#reg-contact').fill('Test Person');await progressNear(.25);
await page.locator('#reg-email').fill('test@example.org');await progressNear(.29);
await page.locator('#reg-password').fill('example-password');await progressNear(.39);
await page.locator('#reg-company').fill('Test Company');await progressNear(.70);
await page.locator('#reg-category').selectOption({label:'Telecommunications'});await progressNear(.83);
assert.equal(await page.locator('#reg-iris').isDisabled(),false);
await page.locator('#reg-iris').click();await progressNear(1);
assert.equal((await state()).category,'Telecommunications');
await page.locator('#signal-tab').click();await progressNear(.12);
assert.equal(await page.locator('#login-continue').isDisabled(),true);
await page.locator('#login-email').fill('test@example.org');await progressNear(.32);
await page.locator('#login-password').fill('example-password');await progressNear(.55);
await page.locator('#demo-role').selectOption('employee');await page.locator('#login-continue').click();
assert.equal(await page.locator('#employee-stage').isVisible(),true);
assert.equal(await page.locator('#login-stage').isVisible(),false);
assert.equal((await state()).loginStage,'employee');
await page.locator('#demo-role').selectOption('supplier');await page.locator('#login-continue').click();await progressNear(.78);
assert.equal(await page.locator('#login-stage').isVisible(),true);
assert.equal(await page.locator('#login-fingerprint').isDisabled(),true);
assert.equal(await page.locator('#signal-pulse-preview').isDisabled(),true);
await page.locator('#login-face').click();await progressNear(.94);
assert.equal(await page.locator('#signal-pulse-preview').isDisabled(),false);
await page.locator('#signal-pulse-preview').click();await progressNear(1);
assert.equal((await state()).loginStage,'face');
assert.equal(externalRequests.length,0);assert.deepEqual(errors,[]);
await page.goto('http://127.0.0.1:4173/compare.html',{waitUntil:'networkidle'});
assert.equal(await page.locator('.pair img').count(),2);
await page.locator('#moment').selectOption('reveal');
assert.equal(await page.locator('#paper').evaluate(img=>img.complete&&img.naturalWidth>0),true);
assert.equal(await page.locator('#signal').evaluate(img=>img.complete&&img.naturalWidth>0),true);
await page.screenshot({path:join(output,'side-by-side-reveal.png'),fullPage:true});
await browser.close();
const report={passed:true,states,errors,externalRequests,comparisons:'side-by-side-reveal.png',fingerprint:'disabled',employee:'no supplier biometric stage',pulse:'explicit demo only'};
await writeFile(join(output,'interaction-check.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));

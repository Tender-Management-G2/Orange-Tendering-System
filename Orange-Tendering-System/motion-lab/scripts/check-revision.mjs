import { chromium } from 'playwright-core';
import { writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';

const root=resolve(import.meta.dirname,'..');
const output=join(root,'evidence','revision');
const browser=await chromium.launch({executablePath:'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe',headless:true,args:['--enable-webgl']});
const report={capturedAt:new Date().toISOString(),browser:browser.version(),errors:[],checks:{},poses:{},camera:{},render:{}};
const assert=(name,condition)=>{report.checks[name]=Boolean(condition);if(!condition)throw new Error(`Failed ${name}`);};
try{
  const context=await browser.newContext({viewport:{width:1440,height:900}});
  const page=await context.newPage();page.on('pageerror',error=>report.errors.push(error.message));
  await page.goto('http://127.0.0.1:4173',{waitUntil:'networkidle'});await page.waitForFunction(()=>window.motionLab);
  for(const [name,p] of [['flat',0],['cardLift',.23],['cardClosed',.38],['buildingMid',.62],['buildingRest',.82],['irisMid',.92],['irisOpen',1]]){
    await page.evaluate(p=>window.motionLab.setProgress(p),p);
    report.poses[name]=await page.evaluate(()=>window.motionLab.getPose());
    report.camera[name]=await page.evaluate(()=>window.motionLab.getCamera());
  }
  const a=report.poses;
  assert('Card rises from planar crease',Math.abs(a.flat.cardHinge.rotation[0])<.001&&a.cardLift.cardHinge.rotation[0]>.55&&Math.abs(a.cardClosed.cardHinge.rotation[0])<.001);
  assert('Sleeve folds on named hinges',Math.abs(a.cardClosed['sleeveHinge.bottom'].rotation[0]-Math.PI)<.01&&Math.abs(a.cardClosed['sleeveHinge.top'].rotation[0]-Math.PI)<.01);
  assert('Walls and roof pass through intermediate angles',a.buildingMid.wallFrontHinge.rotation[0]<-.1&&a.buildingMid.wallFrontHinge.rotation[0]>-1.5&&a.buildingRest.roofHinge.rotation[0]>1.5);
  assert('Iris leaf and blade rotate continuously',a.irisMid['paperIris.attachedLeafHinge'].rotation[0]<-1.4&&a.irisMid['paperIris.bladePivot.0'].rotation[2]<0&&a.irisOpen['paperIris.bladePivot.0'].rotation[2]<-.95);
  await page.evaluate(()=>window.motionLab.setProgress(.82));
  await page.getByRole('button',{name:'↶ Reverse'}).click();await page.waitForTimeout(600);
  report.checks.reverseProgress=await page.evaluate(()=>window.motionLab.getState().progress);
  assert('Reverse playback moves backward',report.checks.reverseProgress<.82);
  await page.getByRole('button',{name:'Ⅱ Pause'}).click();
  await page.evaluate(()=>window.motionLab.setProgress(.82));
  await page.getByLabel('Supplier category').selectOption({label:'Telecommunications'});await page.waitForTimeout(1350);
  assert('Supplier category changes',await page.evaluate(()=>window.motionLab.getState().category==='Telecommunications'));
  await page.screenshot({path:join(output,'paper-telecom-final.png'),fullPage:true});
  await page.getByLabel('Wireframe proof').check();await page.screenshot({path:join(output,'paper-wireframe-final.png'),fullPage:true});
  assert('Wireframe toggle works',await page.evaluate(()=>window.motionLab.getState().wireframe));
  await page.getByLabel('Wireframe proof').uncheck();
  await page.getByLabel('Orbit inspection').check();
  const bounds=await page.locator('#scene').boundingBox();
  await page.mouse.move(bounds.x+bounds.width*.5,bounds.y+bounds.height*.5);await page.mouse.down();
  await page.mouse.move(bounds.x+bounds.width*.7,bounds.y+bounds.height*.56,{steps:30});await page.mouse.up();
  await page.screenshot({path:join(output,'paper-orbit-final.png'),fullPage:true});
  assert('Orbit inspection works',await page.evaluate(()=>window.motionLab.getState().orbit));
  await page.getByLabel('Orbit inspection').uncheck();
  await page.getByLabel('Lighting rig').selectOption('raking');
  await page.screenshot({path:join(output,'paper-raking-light-final.png'),fullPage:true});
  assert('Raking light control works',await page.evaluate(()=>window.motionLab.getState().lightingRig==='raking'));
  await page.getByLabel('Material view').selectOption('clay');
  await page.screenshot({path:join(output,'paper-neutral-clay-final.png'),fullPage:true});
  assert('Neutral clay material view works',await page.evaluate(()=>window.motionLab.getState().materialMode==='clay'));
  await page.getByLabel('Cast shadows').uncheck();
  await page.screenshot({path:join(output,'paper-without-shadows-final.png'),fullPage:true});
  assert('Shadow control works',await page.evaluate(()=>!window.motionLab.getState().shadows));
  await page.getByLabel('Cast shadows').check();
  await page.getByLabel('Material view').selectOption('authored');
  await page.getByLabel('Lighting rig').selectOption('studio');
  await page.getByLabel('Supplier category').selectOption({label:'IT & Electronics'});await page.waitForTimeout(1350);
  await page.evaluate(()=>{document.querySelector('.inspector').scrollTop=0;window.motionLab.setProgress(.76);});
  await page.screenshot({path:join(output,'paper-current-final.png'),fullPage:true});
  await page.evaluate(()=>window.motionLab.setProgress(1));
  await page.screenshot({path:join(output,'iris-current-final.png'),fullPage:true});
  await page.evaluate(()=>window.motionLab.setMode('signal'));
  await page.evaluate(()=>window.motionLab.setProgress(.55));await page.screenshot({path:join(output,'signal-contacts-final.png'),fullPage:true});
  await page.evaluate(()=>window.motionLab.setProgress(1));await page.screenshot({path:join(output,'signal-optics-final.png'),fullPage:true});
  assert('Fingerprint is disabled',await page.getByRole('button',{name:'Fingerprint / Coming soon'}).isDisabled());
  report.render.desktop=await page.evaluate(()=>window.motionLab.getRenderStats());
  await context.close();
  const mobile=await browser.newContext({viewport:{width:390,height:844}});
  const mobilePage=await mobile.newPage();mobilePage.on('pageerror',error=>report.errors.push(error.message));
  await mobilePage.goto('http://127.0.0.1:4173',{waitUntil:'networkidle'});await mobilePage.waitForFunction(()=>window.motionLab);
  await mobilePage.evaluate(()=>{window.motionLab.setMode('signal');window.motionLab.setProgress(1);});
  await mobilePage.screenshot({path:join(output,'signal-optics-mobile-final.png'),fullPage:true});
  report.render.mobile=await mobilePage.evaluate(()=>window.motionLab.getRenderStats());await mobile.close();
  const reduced=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'});
  const reducedPage=await reduced.newPage();await reducedPage.goto('http://127.0.0.1:4173',{waitUntil:'networkidle'});await reducedPage.waitForFunction(()=>window.motionLab);
  assert('Reduced motion starts enabled',await reducedPage.getByLabel('Reduced motion endpoint').isChecked());
  await reducedPage.getByRole('button',{name:'A / Card and sleeve'}).click();
  assert('Reduced motion jumps to shot endpoint',await reducedPage.evaluate(()=>Math.abs(window.motionLab.getState().progress-.39)<.001));await reduced.close();
  const unavailable=await browser.newContext({viewport:{width:390,height:844}});
  await unavailable.addInitScript(()=>{
    const original=HTMLCanvasElement.prototype.getContext;
    HTMLCanvasElement.prototype.getContext=function(kind,...args){return kind==='webgl'||kind==='webgl2'?null:original.call(this,kind,...args);};
  });
  const unavailablePage=await unavailable.newPage();await unavailablePage.goto('http://127.0.0.1:4173',{waitUntil:'domcontentloaded'});
  assert('WebGL fallback is visible',await unavailablePage.locator('#webgl-fallback').isVisible());await unavailable.close();
  assert('No browser page errors',report.errors.length===0);
}finally{await writeFile(join(output,'qa.json'),JSON.stringify(report,null,2));await browser.close();}

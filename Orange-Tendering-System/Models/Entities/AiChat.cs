using System.ComponentModel.DataAnnotations;
using Microsoft.EntityFrameworkCore;

namespace Orange_Tendering_System.Models.Entities
{
    // Floating AI Chat Assistant history. Strictly per user: every query filters by UserId, so a user can never read, continue or
    // delete another user's conversation. This is separate from AI Bid Analysis (AiAnalysis) and from the role-based Clarifications.
    [Index(nameof(UserId), nameof(UpdatedAt))]
    public class AiChatConversation
    {
        public int Id { get; set; }
        [Required, MaxLength(450)] public string UserId { get; set; } = string.Empty;
        public ApplicationUser User { get; set; } = null!;
        [MaxLength(100)] public string? WorkspaceRole { get; set; }
        [Required, MaxLength(200)] public string Title { get; set; } = "New chat";
        public DateTime CreatedAt { get; set; }
        public DateTime UpdatedAt { get; set; }
        public ICollection<AiChatMessage> Messages { get; set; } = new List<AiChatMessage>();
    }

    [Index(nameof(ConversationId), nameof(Id))]
    public class AiChatMessage
    {
        public long Id { get; set; }
        public int ConversationId { get; set; }
        public AiChatConversation Conversation { get; set; } = null!;
        [Required, MaxLength(20)] public string Role { get; set; } = "user";   // user | assistant
        [Required] public string Content { get; set; } = string.Empty;
        public DateTime CreatedAt { get; set; }
        // text (default, null) | data | file | clarify | upload. PayloadJson holds the server-built table, the generated file card
        // or the pending report request; it is written only by server code, never by the model.
        [MaxLength(20)] public string? Kind { get; set; }
        public string? PayloadJson { get; set; }
    }

    // A file the assistant generated for the user (Excel/PDF/Word/PowerPoint) or a document the user uploaded for analysis.
    // Stored under App_Data/AiAssistant (never wwwroot) with a random name; downloads check UserId on the server.
    [Index(nameof(UserId), nameof(CreatedAt)), Index(nameof(ExpiresAt))]
    public class AiChatFile
    {
        public Guid Id { get; set; }
        [Required, MaxLength(450)] public string UserId { get; set; } = string.Empty;
        public ApplicationUser User { get; set; } = null!;
        public int? ConversationId { get; set; }
        public AiChatConversation? Conversation { get; set; }
        [Required, MaxLength(20)] public string Kind { get; set; } = "generated";   // generated | upload
        [Required, MaxLength(200)] public string FileName { get; set; } = string.Empty;
        [Required, MaxLength(100)] public string StorageKey { get; set; } = string.Empty;
        [Required, MaxLength(120)] public string ContentType { get; set; } = "application/octet-stream";
        [MaxLength(10)] public string Format { get; set; } = string.Empty;   // xlsx | pdf | docx | pptx | csv | txt
        public long SizeBytes { get; set; }
        [MaxLength(64)] public string Sha256 { get; set; } = string.Empty;
        public string? ExtractedText { get; set; }   // uploads only: bounded plain text, treated as untrusted data
        public DateTime CreatedAt { get; set; }
        public DateTime ExpiresAt { get; set; }
        public DateTime? DeletedAt { get; set; }
    }

    // Durable retrieval knowledge. Shared documents are never visible until an Admin approves them; personal documents
    // remain owner-scoped. System entries are versioned, reviewed application help generated by the release process.
    [Index(nameof(Scope), nameof(Status), nameof(UpdatedAt))]
    [Index(nameof(OwnerUserId), nameof(Status), nameof(UpdatedAt))]
    public class AiKnowledgeDocument
    {
        public int Id { get; set; }
        [MaxLength(450)] public string? OwnerUserId { get; set; }
        public ApplicationUser? Owner { get; set; }
        [Required, MaxLength(200)] public string Title { get; set; } = string.Empty;
        [Required, MaxLength(200)] public string SourceName { get; set; } = string.Empty;
        [Required, MaxLength(64)] public string SourceSha256 { get; set; } = string.Empty;
        [Required, MaxLength(16)] public string Scope { get; set; } = "Personal"; // Personal | Shared | System
        [Required, MaxLength(24)] public string Status { get; set; } = "PendingApproval"; // PendingApproval | Ready | Rejected | Failed
        [MaxLength(8)] public string Language { get; set; } = "und";
        public int Version { get; set; } = 1;
        [MaxLength(450)] public string? ApprovedByUserId { get; set; }
        public DateTime? ApprovedAt { get; set; }
        public DateTime CreatedAt { get; set; }
        public DateTime UpdatedAt { get; set; }
        public DateTime? DeletedAt { get; set; }
        public ICollection<AiKnowledgeChunk> Chunks { get; set; } = new List<AiKnowledgeChunk>();
    }

    [Index(nameof(DocumentId), nameof(Ordinal), IsUnique = true)]
    public class AiKnowledgeChunk
    {
        public long Id { get; set; }
        public int DocumentId { get; set; }
        public AiKnowledgeDocument Document { get; set; } = null!;
        public int Ordinal { get; set; }
        [Required] public string Text { get; set; } = string.Empty;
        [Required] public string EmbeddingJson { get; set; } = "[]";
        [Required, MaxLength(100)] public string EmbeddingModel { get; set; } = string.Empty;
        public int Dimensions { get; set; }
        [Required, MaxLength(64)] public string ContentSha256 { get; set; } = string.Empty;
    }
}

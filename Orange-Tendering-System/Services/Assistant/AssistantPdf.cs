using MigraDoc.DocumentObjectModel;
using MigraDoc.DocumentObjectModel.Shapes.Charts;
using MigraDoc.DocumentObjectModel.Tables;
using MigraDoc.Rendering;
using Orange_Tendering_System.Services.Reports;

namespace Orange_Tendering_System.Services.Assistant;

// Server-side PDF through the project's existing MigraDoc/PDFsharp stack and the configured report fonts (ReportPdf:FontDirectory,
// default: Windows Arial). Arabic text is shaped and ordered by ArabicText because PDFsharp does not do it.
public sealed class AssistantPdf(OrangeReportRenderer fontsReady)
{
    private readonly OrangeReportRenderer _ = fontsReady;   // its constructor installs the shared PDFsharp font resolver
    private static readonly Color Orange = new(255, 121, 0), Dark = new(31, 31, 31), Grey = new(110, 110, 110), Rule = new(225, 225, 225), Zebra = new(250, 250, 250), Tint = new(255, 241, 229);

    public byte[] Build(AssistantDataset data, ReportMeta meta) => Render(meta, (section, width) => Body(section, width, data, meta), data.Columns.Count > 6);

    // Narrative documents (e.g. an uploaded-document analysis): headed sections of plain paragraphs.
    public byte[] BuildText(ReportMeta meta, IReadOnlyList<(string Heading, string Body)> sections, IReadOnlyList<(string Label, string Value)> facts) =>
        Render(meta, (section, width) =>
        {
            Facts(section, width, facts, meta.Arabic);
            foreach (var (heading, body) in sections)
            {
                Heading(section, heading, meta.Arabic);
                foreach (var paragraph in body.Replace("\r", "").Split("\n\n", StringSplitOptions.RemoveEmptyEntries))
                {
                    var p = section.AddParagraph(); p.Format.SpaceAfter = "5pt";
                    Text(p, paragraph.Trim(), meta.Arabic || ArabicText.HasArabic(paragraph), (int)(width * 5.2));
                }
            }
        }, false);

    private static byte[] Render(ReportMeta meta, Action<Section, double> body, bool landscape)
    {
        var doc = new Document();
        doc.Info.Title = meta.Title; doc.Info.Author = meta.GeneratedBy; doc.Info.Subject = OrangeBrand.Company;
        var normal = doc.Styles[StyleNames.Normal]!; normal.Font.Name = "Orange Sans"; normal.Font.Size = 9;
        var section = doc.AddSection();
        section.PageSetup = doc.DefaultPageSetup.Clone();
        // Explicit A4 dimensions: MigraDoc's Orientation flag alone did not rotate the rendered page.
        section.PageSetup.Orientation = Orientation.Portrait;
        section.PageSetup.PageWidth = Unit.FromCentimeter(landscape ? 29.7 : 21.0);
        section.PageSetup.PageHeight = Unit.FromCentimeter(landscape ? 21.0 : 29.7);
        section.PageSetup.LeftMargin = section.PageSetup.RightMargin = "1.5cm";
        section.PageSetup.TopMargin = "2.2cm"; section.PageSetup.BottomMargin = "1.8cm";
        section.PageSetup.HeaderDistance = "0.8cm"; section.PageSetup.FooterDistance = "0.8cm";
        var width = (landscape ? 29.7 : 21.0) - 3.0;
        var ar = meta.Arabic;

        var header = section.Headers.Primary.AddParagraph();
        header.Format.Font.Size = 8; header.Format.Font.Color = Grey; header.Format.Borders.Bottom.Color = Orange; header.Format.Borders.Bottom.Width = 1.2; header.Format.Borders.Distance = "3pt";
        header.Format.Alignment = ar ? ParagraphAlignment.Right : ParagraphAlignment.Left;
        var brand = header.AddFormattedText(Vis(ar ? OrangeBrand.CompanyAr : OrangeBrand.Company)); brand.Bold = true; brand.Color = Orange;
        header.AddText("   " + Vis(meta.Title));

        var footer = section.Footers.Primary.AddParagraph();
        footer.Format.Font.Size = 8; footer.Format.Font.Color = Grey; footer.Format.Alignment = ParagraphAlignment.Center;
        footer.AddText(Vis(ar ? "سري — للاستخدام الداخلي المصرّح به · " : "Confidential — authorized internal use · "));
        footer.AddPageField(); footer.AddText(" / "); footer.AddNumPagesField();

        var kicker = section.AddParagraph(Vis(ar ? "تقرير مُنشأ بواسطة Orange AI" : "REPORT GENERATED BY ORANGE AI"));
        kicker.Format.Font.Size = 8; kicker.Format.Font.Bold = true; kicker.Format.Font.Color = Orange; Align(kicker, ar);
        var title = section.AddParagraph(); title.Format.Font.Size = 20; title.Format.Font.Bold = true; title.Format.SpaceBefore = "2pt"; title.Format.SpaceAfter = "4pt";
        Text(title, meta.Title, ar, (int)(width * 2.6));
        var line = section.AddParagraph(); line.Format.Borders.Bottom.Color = Orange; line.Format.Borders.Bottom.Width = 2; line.Format.SpaceAfter = "8pt";
        Facts(section, width, [
            (ar ? "تاريخ الإنشاء" : "Generated", meta.Generated),
            (ar ? "بواسطة" : "Generated by", $"{meta.GeneratedBy} · {meta.Role}"),
            (ar ? "النطاق" : "Scope", meta.ScopeNote)], ar);
        body(section, width);

        var renderer = new PdfDocumentRenderer { Document = doc };
        renderer.RenderDocument();
        using var stream = new MemoryStream();
        renderer.PdfDocument.Save(stream, false);
        return stream.ToArray();
    }

    private static void Body(Section section, double width, AssistantDataset data, ReportMeta meta)
    {
        var ar = meta.Arabic;
        if (data.Summary.Count > 0 || data.TotalCount > 0)
        {
            Heading(section, ar ? "الملخص" : "Summary", ar);
            var facts = new List<(string, string)> { (ar ? "عدد السجلات" : "Records", data.Truncated ? (ar ? $"{data.Rows.Count} من {data.TotalCount}" : $"{data.Rows.Count} of {data.TotalCount}") : data.Rows.Count.ToString()) };
            facts.AddRange(data.Summary);
            Facts(section, width, facts, ar);
        }
        if (data.Chart.Count > 1)
        {
            Heading(section, data.ChartTitle ?? (ar ? "التوزيع" : "Breakdown"), ar);
            var chart = new Chart(ChartType.Bar2D) { Width = Unit.FromCentimeter(Math.Min(width, 17)), Height = Unit.FromCentimeter(Math.Clamp(1.2 + data.Chart.Count * 0.75, 4, 9)) };
            var series = chart.SeriesCollection.AddSeries();
            series.Add(data.Chart.Select(x => x.Value).ToArray());
            series.FillFormat.Color = Orange; series.HasDataLabel = true; series.DataLabel.Font.Size = 7;
            chart.XValues.AddXSeries().Add(data.Chart.Select(x => Vis(x.Label.Length > 34 ? x.Label[..33] + "…" : x.Label)).ToArray());
            chart.XAxis.TickLabels.Font.Size = 7; chart.YAxis.TickLabels.Font.Size = 7; chart.YAxis.MajorTickMark = TickMarkType.Outside; chart.YAxis.HasMajorGridlines = true;
            chart.YAxis.MajorGridlines.LineFormat.Color = Rule; chart.PlotArea.LineFormat.Color = Rule;
            section.Add(chart);
            section.AddParagraph().Format.SpaceAfter = "6pt";
        }
        Heading(section, ar ? "البيانات" : "Records", ar);
        if (data.Rows.Count == 0)
        {
            var empty = section.AddParagraph(); Text(empty, data.Empty ?? (ar ? "لا توجد سجلات مطابقة ضمن نطاق صلاحياتك." : "No records match this request in your authorized scope."), ar, 200);
            return;
        }
        var order = Enumerable.Range(0, data.Columns.Count).ToArray();
        if (ar) Array.Reverse(order);   // right-to-left table: first column on the right
        var weights = order.Select(i => data.Columns[i].Width > 0 ? data.Columns[i].Width : 14).ToArray();
        var table = section.AddTable();
        table.Borders.Color = Rule; table.Borders.Width = 0.5; table.Format.Font.Size = data.Columns.Count > 7 ? 7 : 8;
        table.LeftPadding = table.RightPadding = "3pt"; table.TopPadding = table.BottomPadding = "2pt";
        var widths = weights.Select(w => width * w / weights.Sum()).ToArray();
        foreach (var w in widths) table.AddColumn(Unit.FromCentimeter(w));
        var head = table.AddRow(); head.HeadingFormat = true; head.Shading.Color = Dark; head.Format.Font.Color = Colors.White; head.Format.Font.Bold = true;
        for (var c = 0; c < order.Length; c++) Text(head.Cells[c].AddParagraph(), data.Columns[order[c]].Header, ar, (int)(widths[c] * 5.2));
        for (var r = 0; r < data.Rows.Count; r++)
        {
            var row = table.AddRow(); if (r % 2 == 1) row.Shading.Color = Zebra;
            for (var c = 0; c < order.Length; c++)
            {
                var column = data.Columns[order[c]];
                var p = row.Cells[c].AddParagraph();
                var value = OrangeBrand.Cell(data.Rows[r].ElementAtOrDefault(order[c]), column.Kind);
                if (column.Kind is ColumnKind.Number or ColumnKind.Money) { p.AddText(value); p.Format.Alignment = ar ? ParagraphAlignment.Left : ParagraphAlignment.Right; }
                else Text(p, value.Length > 700 ? value[..700] + "…" : value, ar || ArabicText.HasArabic(value), (int)(widths[c] * 5.2));
            }
        }
        if (data.Truncated)
        {
            var note = section.AddParagraph(); note.Format.SpaceBefore = "6pt"; note.Format.Font.Size = 8; note.Format.Font.Color = Grey;
            Text(note, ar ? $"يعرض هذا التقرير أول {data.Rows.Count} سجلًا من أصل {data.TotalCount}." : $"This report shows the first {data.Rows.Count} of {data.TotalCount} records.", ar, 200);
        }
    }

    private static void Heading(Section section, string text, bool ar)
    {
        var p = section.AddParagraph(); p.Format.Font.Size = 12; p.Format.Font.Bold = true; p.Format.Font.Color = Dark;
        p.Format.SpaceBefore = "10pt"; p.Format.SpaceAfter = "4pt"; p.Format.Borders.Bottom.Color = Tint; p.Format.Borders.Bottom.Width = 1;
        Text(p, text, ar, 120);
    }

    private static void Facts(Section section, double width, IEnumerable<(string Label, string Value)> facts, bool ar)
    {
        var table = section.AddTable(); table.Borders.Color = Rule; table.Borders.Width = 0.5; table.Format.Font.Size = 8.5;
        table.LeftPadding = table.RightPadding = "4pt"; table.TopPadding = table.BottomPadding = "2.5pt";
        var labelWidth = Math.Min(6.0, width * 0.32);
        if (ar) { table.AddColumn(Unit.FromCentimeter(width - labelWidth)); table.AddColumn(Unit.FromCentimeter(labelWidth)); }
        else { table.AddColumn(Unit.FromCentimeter(labelWidth)); table.AddColumn(Unit.FromCentimeter(width - labelWidth)); }
        foreach (var (label, value) in facts)
        {
            var row = table.AddRow();
            var labelCell = row.Cells[ar ? 1 : 0]; labelCell.Shading.Color = Tint;
            var l = labelCell.AddParagraph(); l.Format.Font.Color = Grey; Text(l, label, ar, (int)(labelWidth * 5));
            var v = row.Cells[ar ? 0 : 1].AddParagraph(); v.Format.Font.Bold = true; Text(v, value, ar || ArabicText.HasArabic(value), (int)((width - labelWidth) * 5));
        }
    }

    private static string Vis(string text) => ArabicText.HasArabic(text) ? ArabicText.Visual(text) : text;
    private static void Align(Paragraph p, bool rtl) => p.Format.Alignment = rtl ? ParagraphAlignment.Right : ParagraphAlignment.Left;

    // Arabic is pre-wrapped to visual lines (MigraDoc would otherwise wrap the reversed string from the wrong end).
    private static void Text(Paragraph p, string text, bool rtl, int maxChars)
    {
        Align(p, rtl);
        if (!ArabicText.HasArabic(text)) { p.AddText(text); return; }
        var lines = ArabicText.VisualLines(text, Math.Max(8, maxChars));
        for (var i = 0; i < lines.Count; i++) { if (i > 0) p.AddLineBreak(); p.AddText(lines[i]); }
    }
}

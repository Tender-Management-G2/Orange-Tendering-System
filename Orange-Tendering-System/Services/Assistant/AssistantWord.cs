using DocumentFormat.OpenXml;
using DocumentFormat.OpenXml.Packaging;
using DocumentFormat.OpenXml.Wordprocessing;

namespace Orange_Tendering_System.Services.Assistant;

// Real .docx through the Open XML SDK (MIT). Word shapes Arabic itself; RTL paragraphs/tables use bidi properties.
public static class AssistantWord
{
    public static byte[] Build(AssistantDataset data, ReportMeta meta) => Create(meta, (body, ar) =>
    {
        if (data.Summary.Count > 0 || data.TotalCount > 0)
        {
            body.Append(Heading(ar ? "الملخص" : "Summary", ar));
            var facts = new List<(string, string)> { (ar ? "عدد السجلات" : "Records", data.Truncated ? (ar ? $"{data.Rows.Count} من {data.TotalCount}" : $"{data.Rows.Count} of {data.TotalCount}") : data.Rows.Count.ToString()) };
            facts.AddRange(data.Summary);
            foreach (var (label, value) in facts) body.Append(Para(ar, (label + ": ", true, null), (value, false, null)));
        }
        if (data.Chart.Count > 1)
        {
            body.Append(Heading(data.ChartTitle ?? (ar ? "التوزيع" : "Breakdown"), ar));
            body.Append(Table(ar, [ar ? "البند" : "Item", ar ? "القيمة" : "Value"], data.Chart.Select(x => new[] { x.Label, OrangeBrand.Cell(x.Value, ColumnKind.Number) }).ToList(), [70, 30]));
        }
        body.Append(Heading(ar ? "البيانات" : "Records", ar));
        if (data.Rows.Count == 0) body.Append(Para(ar, (data.Empty ?? (ar ? "لا توجد سجلات مطابقة ضمن نطاق صلاحياتك." : "No records match this request in your authorized scope."), false, null)));
        else body.Append(Table(ar, data.Columns.Select(c => c.Header).ToArray(),
            data.Rows.Select(r => data.Columns.Select((c, i) => OrangeBrand.Cell(r.ElementAtOrDefault(i), c.Kind)).ToArray()).ToList(),
            data.Columns.Select(c => c.Width > 0 ? c.Width : 14).ToArray()));
        if (data.Truncated) body.Append(Para(ar, (ar ? $"يعرض هذا المستند أول {data.Rows.Count} سجلًا من أصل {data.TotalCount}." : $"This document shows the first {data.Rows.Count} of {data.TotalCount} records.", false, "6E6E6E")));
    }, data.Columns.Count > 6);

    public static byte[] BuildText(ReportMeta meta, IReadOnlyList<(string Heading, string Body)> sections) => Create(meta, (body, ar) =>
    {
        foreach (var (heading, text) in sections)
        {
            body.Append(Heading(heading, ar));
            foreach (var paragraph in text.Replace("\r", "").Split("\n\n", StringSplitOptions.RemoveEmptyEntries))
                body.Append(Para(ar || AssistantIntentParser.IsArabic(paragraph), (paragraph.Trim(), false, null)));
        }
    }, false);

    private static byte[] Create(ReportMeta meta, Action<Body, bool> fill, bool landscape)
    {
        using var stream = new MemoryStream();
        using (var doc = WordprocessingDocument.Create(stream, WordprocessingDocumentType.Document))
        {
            doc.PackageProperties.Title = meta.Title; doc.PackageProperties.Creator = meta.GeneratedBy; doc.PackageProperties.Created = DateTime.UtcNow;
            var main = doc.AddMainDocumentPart();
            var styles = main.AddNewPart<StyleDefinitionsPart>();
            styles.Styles = new Styles(new DocDefaults(
                new RunPropertiesDefault(new RunPropertiesBaseStyle(new RunFonts { Ascii = "Calibri", HighAnsi = "Calibri", ComplexScript = "Arial" }, new FontSize { Val = "21" }, new FontSizeComplexScript { Val = "21" })),
                new ParagraphPropertiesDefault(new ParagraphPropertiesBaseStyle(new SpacingBetweenLines { After = "80", Line = "276", LineRule = LineSpacingRuleValues.Auto }))));
            var ar = meta.Arabic;
            var footer = main.AddNewPart<FooterPart>();
            footer.Footer = new Footer(new Paragraph(
                new ParagraphProperties(new Justification { Val = JustificationValues.Center }),
                Run(ar ? "سري — للاستخدام الداخلي المصرّح به · صفحة " : "Confidential — authorized internal use · Page ", false, "6E6E6E", 16),
                new SimpleField(Run("1", false, "6E6E6E", 16)) { Instruction = "PAGE" },
                Run(" / ", false, "6E6E6E", 16),
                new SimpleField(Run("1", false, "6E6E6E", 16)) { Instruction = "NUMPAGES" }));
            var body = new Body();
            body.Append(Para(ar, (ar ? OrangeBrand.CompanyAr : OrangeBrand.Company, true, OrangeBrand.Orange)));
            body.Append(new Paragraph(PProps(ar, border: new ParagraphBorders(new BottomBorder { Val = BorderValues.Single, Size = 18, Color = OrangeBrand.Orange, Space = 4 }), spacing: new SpacingBetweenLines { After = "120" }),
                Run(meta.Title, true, OrangeBrand.Dark, 40, ar)));
            body.Append(Para(ar, ((ar ? "تاريخ الإنشاء: " : "Generated: "), true, "6E6E6E"), (meta.Generated, false, "6E6E6E")));
            body.Append(Para(ar, ((ar ? "بواسطة: " : "Generated by: "), true, "6E6E6E"), ($"{meta.GeneratedBy} · {meta.Role}", false, "6E6E6E")));
            body.Append(Para(ar, ((ar ? "النطاق: " : "Scope: "), true, "6E6E6E"), (meta.ScopeNote, false, "6E6E6E")));
            fill(body, ar);
            var size = landscape ? new PageSize { Width = 16838, Height = 11906, Orient = PageOrientationValues.Landscape } : new PageSize { Width = 11906, Height = 16838 };
            body.Append(new SectionProperties(new FooterReference { Type = HeaderFooterValues.Default, Id = main.GetIdOfPart(footer) }, size,
                new PageMargin { Top = 1134, Bottom = 1134, Left = 1020, Right = 1020, Header = 567, Footer = 567 }));
            if (ar) body.GetFirstChild<SectionProperties>()!.Append(new BiDi());
            main.Document = new Document(body);
            main.Document.Save();
        }
        return stream.ToArray();
    }

    private static Run Run(string text, bool bold, string? color, int halfPoints = 0, bool rtl = false)
    {
        var props = new RunProperties();
        if (bold) { props.Append(new Bold()); props.Append(new BoldComplexScript()); }
        if (color != null) props.Append(new Color { Val = color });
        if (halfPoints > 0) { props.Append(new FontSize { Val = halfPoints.ToString() }); props.Append(new FontSizeComplexScript { Val = halfPoints.ToString() }); }
        if (rtl || AssistantIntentParser.IsArabic(text)) props.Append(new RightToLeftText());
        return new Run(props, new Text(Clean(text)) { Space = SpaceProcessingModeValues.Preserve });
    }

    // XML 1.0 cannot carry most control characters; user/database text is cleaned before it is written.
    private static string Clean(string text) => new(text.Where(c => c is '\t' or '\n' or '\r' || (c >= ' ' && c != '￾' && c != '￿')).ToArray());

    // Paragraph properties in the schema order Word requires (keepNext, pBdr, bidi, spacing, jc).
    private static ParagraphProperties PProps(bool rtl, bool keepNext = false, ParagraphBorders? border = null, SpacingBetweenLines? spacing = null, bool justify = true)
    {
        var p = new ParagraphProperties();
        if (keepNext) p.Append(new KeepNext());
        if (border != null) p.Append(border);
        if (rtl) p.Append(new BiDi());
        if (spacing != null) p.Append(spacing);
        if (justify) p.Append(new Justification { Val = rtl ? JustificationValues.Right : JustificationValues.Left });
        return p;
    }

    private static Paragraph Para(bool rtl, params (string Text, bool Bold, string? Color)[] parts)
    {
        var p = new Paragraph(PProps(rtl));
        foreach (var (text, bold, color) in parts) p.Append(Run(text, bold, color, 0, rtl));
        return p;
    }

    private static Paragraph Heading(string text, bool rtl) => new(
        PProps(rtl, keepNext: true, border: new ParagraphBorders(new BottomBorder { Val = BorderValues.Single, Size = 6, Color = "FFD9B8", Space = 2 }), spacing: new SpacingBetweenLines { Before = "240", After = "100" }),
        Run(text, true, OrangeBrand.Dark, 28, rtl));

    private static Table Table(bool rtl, string[] headers, List<string[]> rows, double[] weights)
    {
        var total = weights.Sum();
        var props = new TableProperties();
        if (rtl) props.Append(new BiDiVisual());
        props.Append(new TableWidth { Width = "5000", Type = TableWidthUnitValues.Pct },
            new TableBorders(new TopBorder { Val = BorderValues.Single, Size = 4, Color = OrangeBrand.Rule }, new LeftBorder { Val = BorderValues.Single, Size = 4, Color = OrangeBrand.Rule },
                new BottomBorder { Val = BorderValues.Single, Size = 4, Color = OrangeBrand.Rule }, new RightBorder { Val = BorderValues.Single, Size = 4, Color = OrangeBrand.Rule },
                new InsideHorizontalBorder { Val = BorderValues.Single, Size = 4, Color = OrangeBrand.Rule }, new InsideVerticalBorder { Val = BorderValues.Single, Size = 4, Color = OrangeBrand.Rule }),
            new TableCellMarginDefault(new TopMargin { Width = "40", Type = TableWidthUnitValues.Dxa }, new BottomMargin { Width = "40", Type = TableWidthUnitValues.Dxa }));
        var table = new Table(props);
        var grid = new TableGrid(); foreach (var w in weights) grid.Append(new GridColumn { Width = ((int)(w / total * 9600)).ToString() }); table.Append(grid);
        TableCell Cell(string text, bool header, bool zebra, double weight)
        {
            var cellProps = new TableCellProperties(new TableCellWidth { Width = ((int)(weight / total * 5000)).ToString(), Type = TableWidthUnitValues.Pct });
            if (header || zebra) cellProps.Append(new Shading { Val = ShadingPatternValues.Clear, Fill = header ? OrangeBrand.Dark : "FAFAFA", Color = "auto" });
            var p = new Paragraph(PProps(rtl, spacing: new SpacingBetweenLines { After = "0" }), Run(text, header, header ? "FFFFFF" : null, 18, rtl));
            return new TableCell(cellProps, p);
        }
        table.Append(new TableRow(new OpenXmlElement[] { new TableRowProperties(new CantSplit(), new TableHeader()) }.Concat(headers.Select((h, i) => Cell(h, true, false, weights[i])))));
        for (var r = 0; r < rows.Count; r++) table.Append(new TableRow(new OpenXmlElement[] { new TableRowProperties(new CantSplit()) }.Concat(rows[r].Select((v, i) => Cell(v, false, r % 2 == 1, weights[i])))));
        return table;
    }
}
